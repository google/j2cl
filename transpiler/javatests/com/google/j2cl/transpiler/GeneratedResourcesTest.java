package com.google.j2cl.transpiler;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertThrows;

import com.google.j2cl.common.OutputUtils;
import com.google.j2cl.common.Problems;
import com.google.j2cl.transpiler.backend.Backend;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import org.junit.Rule;
import org.junit.Test;
import org.junit.rules.TemporaryFolder;

public class GeneratedResourcesTest {
  @Rule public final TemporaryFolder temporaryFolder = new TemporaryFolder();

  @Test
  public void preservesResourcesFromBothProcessorOutputLocations() throws Exception {
    Problems problems = new Problems();
    Path destination = temporaryFolder.newFolder().toPath();
    try (var output =
        OutputUtils.initOutput(destination, temporaryFolder.newFolder().toPath(), problems)) {
      var options = options(output, problems);
      write(options.getSourceGenPath(), "example/data.properties", "source=true");
      write(options.getClassGenPath(), "META-INF/data.json", "{\"class\":true}");
      write(options.getSourceGenPath(), "example/Generated.java", "generated source");
      write(options.getClassGenPath(), "example/Generated.class", "generated bytecode");
      J2clTranspiler.transpile(options, problems);
    }
    assertEquals("source=true", Files.readString(destination.resolve("example/data.properties")));
    assertEquals("{\"class\":true}", Files.readString(destination.resolve("META-INF/data.json")));
    assertFalse(Files.exists(destination.resolve("example/Generated.java")));
    assertFalse(Files.exists(destination.resolve("example/Generated.class")));
  }

  @Test
  public void distinguishesJavaScriptSourcesNativeBindingsAndClassResources() throws Exception {
    Problems problems = new Problems();
    Path destination = temporaryFolder.newFolder().toPath();
    try (var output =
        OutputUtils.initOutput(destination, temporaryFolder.newFolder().toPath(), problems)) {
      var options = options(output, problems);
      write(options.getSourceGenPath(), "example/generated.js", "source");
      write(options.getSourceGenPath(), "example/Binding.native.js", "native source");
      write(options.getClassGenPath(), "assets/resource.js", "resource");
      write(options.getClassGenPath(), "assets/resource.native.js", "native resource");
      J2clTranspiler.transpile(options, problems);
    }
    assertEquals("source", Files.readString(destination.resolve("example/generated.js")));
    assertFalse(Files.exists(destination.resolve("example/Binding.native.js")));
    assertFalse(Files.exists(destination.resolve("assets/resource.js")));
    assertFalse(Files.exists(destination.resolve("assets/resource.native.js")));
  }

  @Test
  public void rejectsResourceNamesSharedByTheTwoLocations() throws Exception {
    Problems problems = new Problems();
    try (var output =
        OutputUtils.initOutput(
            temporaryFolder.newFolder().toPath(), temporaryFolder.newFolder().toPath(), problems)) {
      var options = options(output, problems);
      write(options.getSourceGenPath(), "example/data.properties", "source");
      write(options.getClassGenPath(), "example/data.properties", "class");
      assertThrows(Problems.Exit.class, () -> J2clTranspiler.transpile(options, problems));
    }
    assertEquals(
        List.of(
            "Error: Generated resource 'example/data.properties' exists in both source and class"
                + " output."),
        problems.getErrors());
  }

  private static void write(Path root, String name, String content) throws Exception {
    Path file = root.resolve(name);
    Files.createDirectories(file.getParent());
    Files.writeString(file, content);
  }

  private static J2clTranspilerOptions options(OutputUtils.Output output, Problems problems) {
    return J2clTranspilerOptions.builder()
        .setSources(List.of())
        .setNativeSources(List.of())
        .setClasspaths(List.of())
        .setSystem(null)
        .setAnnotationProcessors(List.of())
        .setAnnotationProcessorPath(List.of())
        .setOutput(output)
        .setTargetLabel("")
        .setLibraryInfoOutput(null)
        .setEmitReadableLibraryInfo(false)
        .setEmitReadableSourceMap(false)
        .setSourceMappingPathPrefix("")
        .setGenerateKytheIndexingMetadata(false)
        .setBackend(Backend.CLOSURE)
        .setWasmEntryPointStrings(List.of())
        .setJavacOptions(List.of())
        .setKotlincOptions(List.of())
        .setStrippedAnnotationNames(List.of())
        .setDependencyKlibs(List.of())
        .setFriendKlibs(List.of())
        .setObjCNamePrefix("")
        .setKotlinNativeFrameworkHeaderPath(null)
        .build(problems);
  }
}
